# Função auxiliar para limpar e converter valores numéricos do formato contábil
def parse_br_number(val):
    if val is None:
        return 0.0

    s = str(val).strip()
    if not s or s in ["-", "-------------", "nan", "NaN", "None"]:
        return 0.0

    if isinstance(val, (int, float)):
        return float(val)

    # Remove R$, espaços e caracteres invisíveis de espaço não-separador (\xa0)
    s = s.replace("R$", "").replace("\xa0", "").replace(" ", "").strip()

    # Tratamento de formato brasileiro (ex: 1.234.567,89 ou 1234,89 ou 1.234)
    if "," in s and "." in s:
        if s.find(".") < s.find(","):
            # Formato brasileiro com ponto de milhar e vírgula decimal
            s = s.replace(".", "").replace(",", ".")
        else:
            # Formato americano ou invertido
            s = s.replace(",", "")
    elif "," in s:
        # Apenas vírgula decimal (ex: 1234,56)
        s = s.replace(".", "").replace(",", ".")
    elif s.count(".") > 1:
        # Múltiplos pontos de milhar sem decimais
        s = s.replace(".", "")

    try:
        return float(s)
    except ValueError:
        return 0.0

# Função para limpar NaNs/NaTs e garantir o tipo correto para cada coluna no Google Sheets
def clean_df_for_sheets(df):
  # Identifica colunas que devem ser estritamente numéricas
  colunas_numericas = [
      "Saldo_Anterior", "Creditos", "Debitos", "Saldo_Atual",
      "Previsto", "Realizado", "Valor"
  ]

  for col in df.columns:
    if col in colunas_numericas:
      # Converte para float, garantindo que valores vazios ou inválidos virem 0.0 numérico
      df[col] = pd.to_numeric(df[col], errors='coerce').fillna(0.0)
    else:
      # Para colunas de texto/data, substitui NaNs por string vazia
      df[col] = df[col].replace({np.nan: "", pd.NA: "", None: "", "nan": ""}).astype(str)
      df[col] = df[col].replace("NaT", "").replace("nan", "")

  return df

